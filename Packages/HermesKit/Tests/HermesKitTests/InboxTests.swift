    /// Hermes's note at the end of each background-process wake (`INTERNAL_NOTIFICATION_FOOTER`).
    private static let footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
        + "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"

    /// Hermes's stored rows for one reply that made several tool calls, with narration and
    /// reasoning between them, and started a background process that beat twice before it ended.
    private static func toolHeavyRows(finished: Bool) -> [SessionMessage] {
        func row(_ id: Int, _ role: String, _ text: String, at seconds: Double, calls: [ToolCall] = [],
                 callID: String? = nil, tool: String? = nil, kind: String? = nil, reasoning: String? = nil) -> SessionMessage {
            SessionMessage(id: id, role: role, content: .text(text), toolCalls: calls, toolCallID: callID, toolName: tool,
                           timestamp: t(seconds), reasoning: reasoning, displayKind: kind)
        }
        func call(_ id: String, _ name: String, _ arguments: String) -> ToolCall { ToolCall(id: id, name: name, arguments: arguments) }
        func heartbeat(_ seq: Int, after age: String) -> String {
            "[Background process proc_7 heartbeat #\(seq) — still running after \(age) (next in 60s when there is new "
                + "output; you will also be told when it exits).\nCommand: make   test\nOutput since last heartbeat:\n"
                + "Test Suite 'All tests' started]\n\n" + Self.footer
        }
        var rows = [
            row(1, "user", "Run the tests and tell me how it goes", at: 0),
            row(2, "assistant", "I'll start the suite in the background.", at: 2,
                calls: [call("c1", "terminal", #"{"command":"make test","background":true}"#)]),
            row(3, "tool", #"{"session_id":"proc_7","status":"started"}"#, at: 3, callID: "c1", tool: "terminal"),
            row(4, "assistant", "While it runs, let me read the config.", at: 4,
                calls: [call("c2", "read_file", #"{"path":"Makefile"}"#), call("c3", "search_files", #"{"pattern":"XCTest"}"#)]),
            row(5, "tool", "test: swift test", at: 5, callID: "c2", tool: "read_file"),
            row(6, "tool", "3 matches", at: 6, callID: "c3", tool: "search_files"),
            row(7, "assistant", "", at: 8, calls: [call("c4", "process", #"{"action":"poll","session_id":"proc_7"}"#)],
                reasoning: "Check it started cleanly."),
            row(8, "tool", #"{"status":"running"}"#, at: 9, callID: "c4", tool: "process"),
            row(9, "assistant", "The suite is running. I'll tell you how it went.", at: 10),
            row(10, "user", heartbeat(1, after: "1m"), at: 70, kind: "internal_notification"),
            row(11, "assistant", "[SILENT]", at: 71),
            row(12, "user", heartbeat(2, after: "2m"), at: 130, kind: "internal_notification"),
            row(13, "assistant", "[SILENT]", at: 131),
        ]
        if finished {
            rows += [
                row(14, "user", "[IMPORTANT: Background process proc_7 completed normally (exit code 0).\nCommand: make test\n"
                    + "Output:\nAll tests passed]\n\n" + Self.footer, at: 190, kind: "internal_notification"),
                row(15, "assistant", "All 412 tests passed.", at: 192),
            ]
        }
        return rows
    }

    @Test func aReplyWithManyToolCallsIsOneMessageAndItsRunEventsNone() throws {
        let items = TranscriptBuilder.build(Self.toolHeavyRows(finished: false))
        // Four tool calls with narration and reasoning between them: one reply, one message. The
        // process's heartbeats and the silent replies to them add nothing.
        #expect(UnreadCounter.count(items, after: Self.t(0)) == 1)
        #expect(UnreadCounter.count(items, after: Self.t(20)) == 0)
        let marker = try #require(NewMessagesMarker.find(in: items, since: Self.t(0), seenThrough: nil))
        #expect(marker.count == 1)
        // A heartbeat is a run event: a notice in Hermes's own words, not an automation's message.
        let notices = items.compactMap { item -> Notice? in if case .notice(let notice) = item { notice } else { nil } }
        #expect(notices.map(\.text) == ["Background process output after 1m: make test", "Background process output after 2m: make test"])
        #expect(!items.contains { if case .user(let entry) = $0 { entry.delivery != nil } else { false } })
        // The reply to the process's end is a message.
        let finished = TranscriptBuilder.build(Self.toolHeavyRows(finished: true))
        #expect(UnreadCounter.count(finished, after: Self.t(0)) == 2)
        #expect(UnreadCounter.count(finished, after: Self.t(20)) == 1)
    }

